// Draws text with its baseline area starting at (x, y) in the current projection,
// in the current colour. Expects premultiplied blending (as Overlay.h sets up).
inline void gl_text(const char* s, float x, float y) {
  using namespace fontdata;
  static GLuint tex = 0;
  if (tex == 0 || !glIsTexture(tex)) {
    // One row of glyphs, as premultiplied white.
    std::vector<unsigned char> rgba(size_t(kW) * kCount * kH * 4);
    for (int g = 0; g < kCount; ++g)
      for (int r = 0; r < kH; ++r)
        for (int c = 0; c < kW; ++c) {
          const unsigned char a = kGlyphs[(g * kH + r) * kW + c];
          unsigned char* p = &rgba[((size_t(r) * kCount * kW) + size_t(g) * kW + c) * 4];
          p[0] = p[1] = p[2] = p[3] = a;
        }
    glGenTextures(1, &tex);
    glBindTexture(GL_TEXTURE_2D, tex);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, kW * kCount, kH, 0, GL_RGBA, GL_UNSIGNED_BYTE, rgba.data());
    glBindTexture(GL_TEXTURE_2D, 0);
  }
  if (!s) return;
  glPushAttrib(GL_ENABLE_BIT | GL_TEXTURE_BIT);
  glEnable(GL_TEXTURE_2D);
  glBindTexture(GL_TEXTURE_2D, tex);
  glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
  const float tw = 1.0f / float(kCount);
  x = float(int(x + 0.5f));
  y = float(int(y + 0.5f)) - 2.0f;
  glBegin(GL_QUADS);
  for (; *s; ++s, x += float(kW)) {
    int g = (unsigned char)*s - kFirst;
    if (g < 0 || g >= kCount) g = '?' - kFirst;
    const float u0 = g * tw, u1 = u0 + tw;
    glTexCoord2f(u0, 0); glVertex2f(x, y);
    glTexCoord2f(u1, 0); glVertex2f(x + kW, y);
    glTexCoord2f(u1, 1); glVertex2f(x + kW, y + kH);
    glTexCoord2f(u0, 1); glVertex2f(x, y + kH);
  }
  glEnd();
  glBindTexture(GL_TEXTURE_2D, 0);
  glPopAttrib();
}

